// Traduit un texte d'interface (ou le renvoie tel quel : français, ou donnée saisie par le médecin).
export function t(s) {
  if (lang === 'fr' || typeof s !== 'string' || !/\p{L}/u.test(s)) return s;
  const m = s.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const core = m[2];
  const hit = EN[core];
  if (hit !== undefined) return m[1] + hit + m[3];
  for (const [re, fn] of PATTERNS) {
    const mm = core.match(re);
    if (mm) return m[1] + fn(mm) + m[3];
  }
  return s;
}
